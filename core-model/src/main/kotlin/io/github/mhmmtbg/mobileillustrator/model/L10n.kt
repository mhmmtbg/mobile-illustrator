/** Metni geçerli dile çevirir; [args] varsa `%s` yer tutucularına sırayla yerleştirilir. */
fun tr(text: String, vararg args: Any?): String {
    val s = L10n.translate(text)
    return if (args.isEmpty()) s else String.format(java.util.Locale.ROOT, s, *args)
}

private val numberedDefault = Regex("^(Katman|Çalışma Yüzeyi) (\\d+)$")

/**
 * Uygulamanın kendi verdiği varsayılan adları ("Katman 1", "Adsız"…) gösterim için çevirir.
 * Belgede saklanan ad değişmez; kullanıcının verdiği adlara dokunulmaz.
 */
fun trName(name: String): String {
    if (!L10n.english) return name
    numberedDefault.matchEntire(name)?.let { m ->
        return (if (m.groupValues[1] == "Katman") "Layer " else "Artboard ") + m.groupValues[2]
    }
    return when (name) {
        "Adsız" -> "Untitled"
        "Kırpma grubu" -> "Clip group"
        "Yol", "Grup", "Görsel", "Metin", "Dikdörtgen", "Elips", "Çizgi" -> L10n.translate(name)
        else -> name
    }
}
